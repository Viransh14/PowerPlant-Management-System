-- Power Plant Management System
-- Run this only if these tables do NOT already exist in your Oracle account.
-- Connect to the intended student schema first in SQL*Plus.
-- Sample data is intentionally not inserted automatically.

CREATE TABLE POWER_PLANT (
    PLANT_ID NUMBER PRIMARY KEY,
    PLANT_NAME VARCHAR2(100) NOT NULL,
    LOCATION VARCHAR2(100),
    CAPACITY_MW NUMBER
);

CREATE TABLE GENERATOR (
    GENERATOR_ID NUMBER PRIMARY KEY,
    PLANT_ID NUMBER REFERENCES POWER_PLANT(PLANT_ID),
    GENERATOR_NAME VARCHAR2(100),
    STATUS VARCHAR2(20)
);

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID NUMBER PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(100),
    ROLE VARCHAR2(50),
    PLANT_ID NUMBER REFERENCES POWER_PLANT(PLANT_ID)
);

CREATE TABLE GENERATION_RECORD (
    RECORD_ID NUMBER PRIMARY KEY,
    PLANT_ID NUMBER REFERENCES POWER_PLANT(PLANT_ID),
    GENERATION_DATE DATE,
    UNITS_GENERATED NUMBER
);

